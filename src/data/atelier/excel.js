// Construit l'objet { A1: …, B1: … } d'un défi
export function buildCells(challenge) {
  const cells = {}
  challenge.rows.forEach((row, r) =>
    row.forEach((value, c) => {
      if (value !== undefined && value !== null && value !== '') cells[`${String.fromCharCode(65 + c)}${r + 1}`] = value
    }),
  )
  return { ...cells, ...challenge.extra }
}
